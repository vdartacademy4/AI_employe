import { logger } from '../../core/logger';
import { prisma } from '../../core/prisma';
import { ConflictError } from '../../core/errors';
import {
  type DailyAnswerType,
  type QuestionSetSource,
  type QuestionTopic,
} from '../../core/enums';
import {
  DAYS_PER_CYCLE,
  QUESTION_BANK,
  QUESTIONS_PER_DAY,
  type BankQuestion,
} from './question-bank';

/** One question of a day's set, as stored. */
export interface SelectedQuestion {
  key: string;
  prompt: string;
  answerType: DailyAnswerType;
  topic: QuestionTopic;
}

export interface DailySetView {
  id: string;
  responseDate: string;
  source: QuestionSetSource;
  model: string | null;
  note: string | null;
  questions: Array<{
    id: string;
    prompt: string;
    answerType: DailyAnswerType;
    helpText: string | null;
    position: number;
    topic: QuestionTopic | null;
  }>;
}

/**
 * Builds and stores the five questions asked on each UTC day.
 *
 * The rules this service exists to enforce:
 *
 *  - **Everyone sees the same five on a given day.** The set is written once
 *    and frozen, so an employee's answers are comparable with everyone else's
 *    and a question's wording can never change after it has been answered.
 *  - **Exactly five, drawn from the fixed 20-question bank.** Not the whole
 *    bank: an employee is asked about their day, not made to fill in a form.
 *  - **A question is never asked on consecutive days.** The bank holds 20
 *    questions and 5 are asked per day, so a full cycle is 4 days long and each
 *    question is used once per cycle. Rotation is a hard guarantee here rather
 *    than a preference, because asking about workload five days running is what
 *    makes a daily pulse get ignored.
 *
 * Selection is a pure function of the date, so the same day always produces the
 * same five questions whether it is computed by the first employee to open the
 * pulse or regenerated by HR afterwards.
 */
export class DailyQuestionGenerator {
  /**
   * The set for `responseDate`, creating it on first use.
   *
   * Two employees opening the same day at the same moment will both reach the
   * creation path. The unique constraint on `DailyQuestionSet.responseDate` is
   * what decides between them: the loser catches the violation and reads the
   * winner's set, so the work is done once per day, not once per employee.
   */
  async setForDate(responseDate: Date): Promise<DailySetView> {
    const existing = await this.findSet(responseDate);
    if (existing) return existing;
    return this.createSet(responseDate);
  }

  /** The stored set for a date, or null. Never creates one. */
  async findSet(responseDate: Date): Promise<DailySetView | null> {
    const row = await prisma.dailyQuestionSet.findUnique({
      where: { responseDate },
      include: { questions: { orderBy: { position: 'asc' } } },
    });
    return row ? toSetView(row) : null;
  }

  private async createSet(responseDate: Date): Promise<DailySetView> {
    const selected = await this.select(responseDate);

    try {
      const row = await prisma.dailyQuestionSet.create({
        data: {
          responseDate,
          source: 'BANK',
          model: null,
          note: null,
          questions: {
            create: selected.map((question, index) => ({
              prompt: question.prompt,
              answerType: question.answerType,
              helpText: null,
              position: index + 1,
              theme: question.topic,
              isActive: true,
            })),
          },
        },
        include: { questions: { orderBy: { position: 'asc' } } },
      });
      logger.info('Daily question set created', {
        responseDate: responseDate.toISOString(),
        questions: selected.map((question) => question.key),
      });
      return toSetView(row);
    } catch (error) {
      if (isUniqueViolation(error)) {
        // Another request won the race. Its set is the one everyone sees.
        const winner = await this.findSet(responseDate);
        if (winner) return winner;
      }
      throw error;
    }
  }

  /**
   * Replaces the set for a date with a freshly rotated one.
   *
   * HR-only, and refused for any day that already has responses: regenerating
   * would strand those answers against questions nobody was ever asked, which
   * quietly corrupts every aggregate built from them.
   */
  async regenerateSet(responseDate: Date): Promise<DailySetView> {
    const existing = await this.findSet(responseDate);
    if (existing) {
      const responses = await prisma.dailyQuestionResponse.count({ where: { responseDate } });
      if (responses > 0) {
        throw new ConflictError(
          `${responses} response(s) already exist for ${responseDate.toISOString().slice(0, 10)}. ` +
            'Questions can only be regenerated for a day nobody has answered.',
        );
      }
      await prisma.dailyQuestionSet.delete({ where: { id: existing.id } });
    }
    return this.createSet(responseDate);
  }

  /** Recent sets, newest first, so HR can see how the rotation is going. */
  async recentSets(limit = 14): Promise<DailySetView[]> {
    const rows = await prisma.dailyQuestionSet.findMany({
      orderBy: { responseDate: 'desc' },
      take: limit,
      include: { questions: { orderBy: { position: 'asc' } } },
    });
    return rows.map(toSetView);
  }

  /**
   * Picks the day's five from the bank, avoiding the previous day's five.
   *
   * The previous day's prompts are read from the database rather than recomputed
   * so the guarantee holds even for a day that was rotated by hand, or for a day
   * generated before the bank changed.
   */
  private async select(responseDate: Date): Promise<SelectedQuestion[]> {
    const previousDay = new Date(responseDate.getTime() - 86_400_000);
    const previous = await prisma.dailyQuestionSet.findUnique({
      where: { responseDate: previousDay },
      select: { questions: { select: { prompt: true } } },
    });
    const previousPrompts = new Set((previous?.questions ?? []).map((question) => question.prompt));
    return selectForDate(responseDate, previousPrompts);
  }
}

/**
 * The pure selection rule, exposed for testing.
 *
 * Round-robins through a per-cycle shuffle of the bank, which gives near-even
 * coverage across a cycle, then removes anything asked the day before and
 * backfills from the same cycle's remaining questions. The filtering is what
 * makes the no-consecutive-repeat rule hold at the seam between two cycles,
 * where two independently shuffled orders would otherwise overlap.
 */
export function selectForDate(
  responseDate: Date,
  previousPrompts?: ReadonlySet<string>,
): SelectedQuestion[] {
  const order = cycleOrder(responseDate);
  const start = positionInCycle(responseDate) * QUESTIONS_PER_DAY;

  const chosen = order.slice(start, start + QUESTIONS_PER_DAY);

  // Rotation already guarantees a question is not asked two days running. This
  // filter exists for the one case rotation cannot see: HR regenerating a day by
  // hand, which can pick a set that overlaps the day after it. It is applied
  // after the slice is taken, so it can only ever remove a question - it never
  // reaches into the next day's slice and reintroduce a repeat.
  if (!previousPrompts || previousPrompts.size === 0) return chosen;

  const kept = chosen.filter((question) => !previousPrompts.has(question.prompt));

  // Five questions is the contract an employee is promised, so a shortage is
  // made up from the rest of the cycle rather than shown as a short form.
  // The backfill skips yesterday's prompts for the same reason the slice filter
  // does: topping up from the whole order without the check would reintroduce
  // exactly the repeat this function exists to prevent. Fifteen of the twenty
  // are always available, so this cannot run short.
  if (kept.length < QUESTIONS_PER_DAY) {
    for (const question of order) {
      if (kept.length >= QUESTIONS_PER_DAY) break;
      if (kept.includes(question)) continue;
      if (previousPrompts.has(question.prompt)) continue;
      kept.push(question);
    }
  }

  // Unreachable in normal operation: yesterday holds five prompts, so fifteen of
  // the twenty are always free and the backfill above completes. If it ever were
  // reached, the choice is between a short form and a repeat, and five questions
  // is the promise made to the employee. Falls back to the unfiltered slice.
  if (kept.length < QUESTIONS_PER_DAY) {
    logger.warn('Daily question exclusion left a short set, using the rotation as-is', {
      responseDate: responseDate.toISOString(),
      excluded: previousPrompts.size,
      recovered: kept.length,
    });
    return chosen;
  }

  return kept;
}

/**
 * The bank's order for a date's cycle.
 *
 * A single seeded permutation is rotated rather than reshuffled per cycle.
 * Reshuffling independently would let two cycles overlap at their seam, and the
 * exclusion filter cannot repair that without itself pulling in repeats; a
 * rotation makes the four days of every cycle tile the bank exactly once, and
 * makes the seam between two cycles land on different questions by
 * construction.
 */
function cycleOrder(responseDate: Date): BankQuestion[] {
  const cycle = Math.floor(dayNumber(responseDate) / DAYS_PER_CYCLE);
  const offset = cycle * QUESTIONS_PER_DAY;
  const base = seededShuffle(QUESTION_BANK, 0);
  return [...base.slice(offset % base.length), ...base.slice(0, offset % base.length)];
}

/** Which of the cycle's four days this is, counting forwards from the epoch. */
function positionInCycle(responseDate: Date): number {
  const remaining = dayNumber(responseDate) % DAYS_PER_CYCLE;
  return (remaining + DAYS_PER_CYCLE) % DAYS_PER_CYCLE;
}

function dayNumber(responseDate: Date): number {
  return Math.floor(responseDate.getTime() / 86_400_000);
}

/**
 * A deterministic shuffle for a given seed.
 *
 * Seeded rather than random so that a day's questions depend only on the date:
 * two requests for the same day, or a regeneration, must not invent a different
 * set for the same people.
 */
export function seededShuffle<T>(items: readonly T[], seed: number): T[] {
  const result = [...items];
  let state = (seed * 2_654_435_761 + 1) >>> 0;

  for (let index = result.length - 1; index > 0; index -= 1) {
    state = (state * 1_664_525 + 1_013_904_223) >>> 0;
    const swap = state % (index + 1);
    const a = result[index]!;
    result[index] = result[swap]!;
    result[swap] = a;
  }

  return result;
}

type SetRow = {
  id: string;
  responseDate: Date;
  source: string;
  model: string | null;
  note: string | null;
  questions: Array<{
    id: string;
    prompt: string;
    answerType: string;
    helpText: string | null;
    position: number;
    theme: string | null;
  }>;
};

function toSetView(row: SetRow): DailySetView {
  return {
    id: row.id,
    responseDate: row.responseDate.toISOString(),
    source: row.source as QuestionSetSource,
    model: row.model,
    note: row.note,
    questions: row.questions.map((question) => ({
      id: question.id,
      prompt: question.prompt,
      answerType: question.answerType as DailyAnswerType,
      helpText: question.helpText,
      position: question.position,
      topic: (question.theme as QuestionTopic | null) ?? null,
    })),
  };
}

function isUniqueViolation(error: unknown): boolean {
  return (
    typeof error === 'object' &&
    error !== null &&
    'code' in error &&
    (error as { code: string }).code === 'P2002'
  );
}